// Builds targets/tokenrouter.json from TokenRouter's public pricing endpoint, keyed by OpenRouter model ids.
// Usage: node scripts/build-tokenrouter-table.mjs [--openrouter-models path/to/openrouter-models.json]
//
// Pricing formula (new-api format, verified 2026-11-05 against TokenRouter's public model pages):
//   USD per 1M input tokens  = model_ratio * 2
//   USD per 1M output tokens = input * completion_ratio
//   USD per 1M cached input  = input * cache_ratio
// Only per-token text models that accept /v1/chat/completions ("openai" endpoint type) are included.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const orArg = args.indexOf("--openrouter-models");
const today = new Date().toISOString().slice(0, 10);

async function getJson(url) {
  const r = await fetch(url, { headers: { "user-agent": "routearena-build" } });
  if (!r.ok) throw new Error(`${url} -> HTTP ${r.status}`);
  return r.json();
}

const pricing = await getJson("https://api.tokenrouter.com/api/pricing");
const orModels = orArg >= 0 ? JSON.parse(fs.readFileSync(args[orArg + 1], "utf8")) : await getJson("https://openrouter.ai/api/v1/models");
const orIds = new Set((orModels.data ?? []).map((m) => String(m.id).toLowerCase()));

/** Map a TokenRouter model_name to an OpenRouter id, or null. */
function toOpenRouterId(name) {
  const n = name.toLowerCase();
  if (orIds.has(n)) return n;
  const candidates = [];
  // bare "claude-sonnet-5-5" -> "anthropic/claude-sonnet-5.5"; "claude-opus-4-8" -> "anthropic/claude-opus-4.8"
  const claude = n.match(/^claude-(haiku|sonnet|opus)-(\d+)(?:-(\d+))?$/);
  if (claude) candidates.push(`anthropic/claude-${claude[1]}-${claude[2]}${claude[3] ? "." + claude[3] : ""}`);
  if (n.startsWith("minimax-")) candidates.push(`minimax/${n}`);
  if (n.startsWith("qwen")) candidates.push(`qwen/${n}`);
  if (n.startsWith("gpt-")) candidates.push(`openai/${n}`);
  if (!n.includes("/")) candidates.push(...[...orIds].filter((id) => id.endsWith("/" + n)));
  for (const c of candidates) if (orIds.has(c)) return c;
  return null;
}

const EXCLUDE_TAGS = /image|video|embedding|audio|tts|speech/i;
const models = {};
const dropped = [];
for (const m of pricing.data) {
  const eps = m.supported_endpoint_types ?? [];
  const perToken = m.quota_type === 0;
  const textual = !EXCLUDE_TAGS.test(m.tags ?? "") && !EXCLUDE_TAGS.test(m.model_name) && !/embedding/.test(m.model_name);
  if (!eps.includes("openai") || !perToken || !textual) {
    dropped.push({ id: m.model_name, reason: !eps.includes("openai") ? `endpoints: ${eps.join(",") || "none"}` : !perToken ? "per-request billing" : "not a text model" });
    continue;
  }
  const input = +(m.model_ratio * 2).toFixed(6);
  const output = +(input * (m.completion_ratio ?? 1)).toFixed(6);
  const cached = m.cache_ratio ? +(input * m.cache_ratio).toFixed(6) : undefined;
  const key = toOpenRouterId(m.model_name);
  if (!key) {
    dropped.push({ id: m.model_name, reason: "no matching OpenRouter id (kept out of the explicit map)" });
    continue;
  }
  const entry = { id: m.model_name, input_per_m: input, output_per_m: output };
  if (cached !== undefined) entry.cached_input_per_m = cached;
  if ((pricing.tiered_pricing ?? {})[m.model_name]) entry.note = "tiered pricing on TokenRouter; base tier shown";
  // Prefer an id that already exists if two TokenRouter names map to the same OpenRouter id; keep the cheaper output price.
  if (!models[key] || models[key].output_per_m > output) models[key] = entry;
}

const out = {
  id: "tokenrouter",
  name: "TokenRouter",
  baseUrl: "https://api.tokenrouter.com/v1",
  keyEnv: "TOKENROUTER_API_KEY",
  supportsFreeCredits: true,
  judgeModel: "openai/gpt-4o-mini",
  pricesSource: "https://api.tokenrouter.com/api/pricing",
  pricesCaptured: today,
  modelsEndpoint: true,
  notes: "Generated by scripts/build-tokenrouter-table.mjs. Keys are OpenRouter ids; ids are TokenRouter model names. Prices: model_ratio*2 USD/M input, *completion_ratio output. Only /v1/chat/completions-capable per-token text models.",
  models: Object.fromEntries(Object.entries(models).sort(([a], [b]) => a.localeCompare(b))),
};
fs.mkdirSync(path.join(root, "targets"), { recursive: true });
fs.writeFileSync(path.join(root, "targets", "tokenrouter.json"), JSON.stringify(out, null, 2) + "\n");
fs.writeFileSync(path.join(root, "docs", "tokenrouter-dropped-models.json"), JSON.stringify({ captured: today, dropped }, null, 2) + "\n");
console.log(`tokenrouter.json: ${Object.keys(models).length} mapped models; ${dropped.length} dropped (see docs/tokenrouter-dropped-models.json)`);
