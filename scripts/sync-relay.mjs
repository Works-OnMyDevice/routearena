// Copies the files the relay shares with the CLI so relay/ deploys as a self-contained Workers project.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lib = path.join(root, "relay", "lib");
fs.mkdirSync(lib, { recursive: true });
const read = (p) => fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");

// report renderer (dependency-free TS; swap the type-only import so it compiles standalone)
let html = read(path.join(root, "src", "report", "html.ts"));
html = html.replace(/import type (\{[^}]*\}) from "\.\/aggregate\.js";\n/, 'import type $1 from "./reportTypes";\n');
fs.writeFileSync(path.join(lib, "reportHtml.ts"), "// GENERATED by scripts/sync-relay.mjs from src/report/html.ts. Do not edit here.\n" + html);

// types the renderer needs
const agg = read(path.join(root, "src", "report", "aggregate.ts"));
const typesOnly = agg
  .replace(/import[^\n]*\n/g, "")
  .replace(/export function quantiles[\s\S]*?\n}\n/, "")
  .replace(/function ok\([\s\S]*$/, "");
// Stand-ins for the types aggregate.ts imports from other modules; the relay renders aggregates, never log records.
const standIns = "type SideResult = Record<string, unknown>;\nexport interface TokenTotals { prompt_tokens: number; completion_tokens: number; cached_tokens: number; reasoning_tokens: number }\n";
fs.writeFileSync(path.join(lib, "reportTypes.ts"), "// GENERATED by scripts/sync-relay.mjs from src/report/aggregate.ts (types only).\n" + standIns + typesOnly);

// price table and agent protocol
fs.copyFileSync(path.join(root, "targets", "tokenrouter.json"), path.join(lib, "tokenrouter-prices.json"));
const agents = read(path.join(root, "AGENTS.md"));
fs.writeFileSync(path.join(lib, "agents.ts"), "// GENERATED by scripts/sync-relay.mjs from AGENTS.md. Do not edit here.\nexport const AGENTS_TXT = " + JSON.stringify(agents) + ";\n");
try {
  fs.unlinkSync(path.join(lib, "agents.txt"));
} catch {
  /* already gone */
}
console.log("synced relay/lib: reportHtml.ts, reportTypes.ts, tokenrouter-prices.json, agents.ts");
